    printJSON(basicLake(latest: items[0], now: now))
    printJSON(basicLake(latest: nil, now: now))
    printJSON(copiedActivityPayload(items[1], features: HostFeatures(lake: true, lakeLayout: true, imageAssets: true, presentSneakPeek: true)))
    return 0
}

private func runCheck() -> Int32 {
    let store = ClipStore()
    print("history: \(store.items.count) item(s), \(store.items.filter(\.pinned).count) pinned")
    print("accessibility (for Paste): \(AXIsProcessTrusted())")
    print("pasteboard types: \(NSPasteboard.general.types?.map(\.rawValue).joined(separator: ", ") ?? "none")")
    return 0
}

@main
private enum Main {
    static func main() {
        let arguments = Array(CommandLine.arguments.dropFirst())

        if arguments.first == "--demo-json" {
            exit(runDemoJSON())
        }
        if arguments.first == "--check" {
            exit(runCheck())
        }

        guard let socketPath = ProcessInfo.processInfo.environment[socketEnvironmentKey],
              !socketPath.isEmpty else {
            fputs("\(pluginName): \(PluginError.socketPathMissing)\n", stderr)
            exit(64)
        }

        do {
            let features = HostFeatures.current
            try DynaPastePlugin(client: JSONSocketClient(socketPath: socketPath, maxFrameSize: features.maxFrameSize)).run()
        } catch {
            fputs("\(pluginName): \(error)\n", stderr)
            exit(65)
        }
    }
}
