/// The lake's content for the given state, without asset commands.
private func lakeLayout(
    items: [ClipItem],
    filter: ClipFilter,
    hasUnpinned: Bool,
    store: ClipStore,
    assetIDs: [String: String],
    copiedID: String?,
    isConfirmingClear: Bool,
    unpinnedCount: Int,
    glanceItems: [ClipItem],
    now: Date
) -> [String: Any] {
    // The rows say what they are; the icon and name only take room from them.
    var lake: [String: Any] = [
        "hideHeader": true,
        "glance": glanceDesign(items: glanceItems, store: store, assetIDs: assetIDs, copiedID: copiedID)
    ]
    guard !items.isEmpty || filter != .all else {
        lake["content"] = emptyContent()
        return lake
    }

    if isConfirmingClear {
        lake["bottom"] = [centered(clearConfirmation(count: unpinnedCount), id: "clear-centered")]
    }

    let bar = toolbar(filter: filter, canClear: hasUnpinned)
    guard !items.isEmpty else {
        lake["content"] = [bar] + emptyContent("No \(filter.title.lowercased()) yet", symbol: filter.symbol)
        return lake
    }

    var textBudget = maxDragTextBudget
    let rows = items.map { item in
        row(
            item,
            assetID: assetIDs[item.id],
            now: now,
            copied: copiedID == item.id,
            drag: dragItem(for: item, store: store, textBudget: &textBudget)
        )
    }
    lake["content"] = [bar, ["type": "scroll", "id": "history", "spacing": 10, "softFade": "both", "children": rows]]
    return lake
}

