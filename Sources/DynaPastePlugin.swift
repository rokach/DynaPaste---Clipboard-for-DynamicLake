    guard let latest else {
        return lakePayload([
            "leftSlot": ["type": "image", "source": "appIcon"],
            "title": ["type": "text", "text": "Nothing copied yet"],
            "subtitle": ["type": "text", "text": "Copies appear here"]
        ])
    }
    return lakePayload([
        "leftSlot": ["type": "image", "source": "sfSymbol", "systemImage": symbol(of: latest), "tint": tint(of: latest)],
        "title": ["type": "text", "text": title(of: latest)],
        "subtitle": ["type": "text", "text": subtitle(of: latest, now: now)],
        "rightSlot": ["type": "button", "systemImage": "doc.on.doc", "tint": "blue", "actionID": "copy:\(latest.id)"]
    ])
