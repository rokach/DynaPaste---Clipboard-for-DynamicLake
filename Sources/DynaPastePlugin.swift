// MARK: - History

private enum ClipKind: String, Codable {
    case text
    case link
    case image
    case files
}

private struct ClipItem: Codable, Equatable {
    var id: String
    var kind: ClipKind
    var text: String?
    var filePaths: [String]?
    /// PNG in the store's blobs folder.
    var imageFile: String?
    var imageSize: CGSize?
    var sourceApp: String?
    var date: Date
    var pinned: Bool

    /// What's compared to find a re-copy of an existing item.
    var contentKey: String {
        switch kind {
        case .text, .link: return "t:\(text ?? "")"
        case .files: return "f:\((filePaths ?? []).joined(separator: "\n"))"
        case .image: return "i:\(imageFile ?? id)"
        }
    }
}

private final class ClipStore {
    private(set) var items: [ClipItem] = []
    private let folder: URL
    private var historyURL: URL { folder.appendingPathComponent("history.json") }
    var blobsFolder: URL { folder.appendingPathComponent("Images", isDirectory: true) }

    init() {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first
            ?? FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Library/Application Support")
        folder = base.appendingPathComponent("DynaPaste", isDirectory: true)
        try? FileManager.default.createDirectory(at: blobsFolder, withIntermediateDirectories: true)
        load()
    }

    /// Pinned first, then newest first.
    var ordered: [ClipItem] {
        items.filter(\.pinned) + items.filter { !$0.pinned }
    }

    func item(_ id: String) -> ClipItem? {
        items.first { $0.id == id }
    }

    /// Returns false when nothing changed.
    @discardableResult
    func add(_ item: ClipItem, limit: Int) -> Bool {
        var item = item
        if let existing = items.firstIndex(where: { $0.contentKey == item.contentKey }) {
            item.id = items[existing].id
            item.pinned = items[existing].pinned
            removeBlobIfUnused(of: items[existing], replacingWith: item)
            items.remove(at: existing)
        }
        items.insert(item, at: 0)
        trim(limit: limit)
        save()
        return true
    }

    func touch(_ id: String) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        var item = items.remove(at: index)
        item.date = Date()
        items.insert(item, at: 0)
        save()
    }

    func togglePin(_ id: String) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].pinned.toggle()
        save()
    }

    func delete(_ id: String) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        let item = items.remove(at: index)
        removeBlob(of: item)
        save()
    }

    /// Pinned items stay.
    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(removeBlob)
        items.removeAll { !$0.pinned }
        save()
    }

    func trim(limit: Int) {
        var unpinnedCount = 0
        items.removeAll { item in
            guard !item.pinned else { return false }
            unpinnedCount += 1
            if unpinnedCount > limit {
                removeBlob(of: item)
                return true
            }
            return false
        }
    }

    func imageURL(for item: ClipItem) -> URL? {
        item.imageFile.map { blobsFolder.appendingPathComponent($0) }
    }

    private func removeBlob(of item: ClipItem) {
        guard let url = imageURL(for: item) else { return }
        try? FileManager.default.removeItem(at: url)
        let folder = url.deletingLastPathComponent()
        if folder.standardizedFileURL != blobsFolder.standardizedFileURL {
            try? FileManager.default.removeItem(at: folder)
        }
    }

    private func removeBlobIfUnused(of old: ClipItem, replacingWith new: ClipItem) {
        if old.imageFile != new.imageFile { removeBlob(of: old) }
    }

    private func load() {
        guard let data = try? Data(contentsOf: historyURL) else { return }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        items = (try? decoder.decode([ClipItem].self, from: data)) ?? []
    }

    func save() {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        guard let data = try? encoder.encode(items) else { return }
        try? data.write(to: historyURL, options: .atomic)
    }
}

// MARK: - Pasteboard

private final class PasteboardWatcher {
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int

    init() {
        lastChangeCount = pasteboard.changeCount
    }

    /// Our own writes aren't new copies.
    func ignoreCurrentChange() {
        lastChangeCount = pasteboard.changeCount
    }

    /// The new copy, if the pasteboard changed and it's something DynaPaste keeps.
    func poll(settings: PluginSettings, store: ClipStore) -> ClipItem? {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return nil }
        let types = pasteboard.types?.map(\.rawValue) ?? []
        // Apps clear the pasteboard and then write; only the clear bumps changeCount, so look again next poll.
        guard !types.isEmpty else { return nil }
        lastChangeCount = changeCount

        if settings.ignoreConcealed, types.contains(where: concealedTypes.contains) {
            return nil
        }

        let sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName
        let id = UUID().uuidString.lowercased()

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return ClipItem(id: id, kind: .files, filePaths: urls.map(\.path), sourceApp: sourceApp, date: Date(), pinned: false)
        }

        // The source lists its richest type first, so an image ahead of text is an image copy.
        let imageIndex = types.firstIndex { $0 == NSPasteboard.PasteboardType.png.rawValue || $0 == NSPasteboard.PasteboardType.tiff.rawValue }
        let textIndex = types.firstIndex { $0 == NSPasteboard.PasteboardType.string.rawValue }
        if let imageIndex, textIndex.map({ imageIndex < $0 }) ?? true {
            guard settings.saveImages else { return nil }
            return imageItem(id: id, sourceApp: sourceApp, store: store)
        }

        guard var text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return nil
        }
        if text.count > maxStoredTextLength {
            text = String(text.prefix(maxStoredTextLength))
        }
        let kind: ClipKind = isLink(text) ? .link : .text
        return ClipItem(id: id, kind: kind, text: text, sourceApp: sourceApp, date: Date(), pinned: false)
    }

    private func imageItem(id: String, sourceApp: String?, store: ClipStore) -> ClipItem? {
        let data = pasteboard.data(forType: .png)
            ?? pasteboard.data(forType: .tiff).flatMap { NSBitmapImageRep(data: $0)?.representation(using: .png, properties: [:]) }
        guard let data, data.count <= maxStoredImageBytes,
              let rep = NSBitmapImageRep(data: data) else {
            return nil
        }
        // Its own folder, so dragging it out gives a readable file name.
        let formatter = DateFormatter()
        formatter.dateFormat = "yyyy-MM-dd 'at' HH.mm.ss"
        let fileName = "\(id)/Copied Image \(formatter.string(from: Date())).png"
        let url = store.blobsFolder.appendingPathComponent(fileName)
        do {
            try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try data.write(to: url, options: .atomic)
        } catch {
            return nil
        }
        return ClipItem(
            id: id,
            kind: .image,
            imageFile: fileName,
            imageSize: CGSize(width: rep.pixelsWide, height: rep.pixelsHigh),
            sourceApp: sourceApp,
            date: Date(),
            pinned: false
        )
    }

    func write(_ item: ClipItem, store: ClipStore) -> Bool {
        pasteboard.clearContents()
        let written: Bool
        switch item.kind {
        case .text, .link:
            written = pasteboard.setString(item.text ?? "", forType: .string)
        case .files:
            let urls = (item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            written = pasteboard.writeObjects(urls)
        case .image:
            guard let url = store.imageURL(for: item), let data = try? Data(contentsOf: url) else {
                written = false
                break
            }
            written = pasteboard.setData(data, forType: .png)
            if let tiff = NSImage(data: data)?.tiffRepresentation {
                pasteboard.setData(tiff, forType: .tiff)
            }
        }
        ignoreCurrentChange()
        return written
    }
}

private func isLink(_ text: String) -> Bool {
    let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
    guard !trimmed.contains(where: \.isWhitespace),
          let url = URL(string: trimmed),
          let scheme = url.scheme?.lowercased() else {
        return false
    }
    return ["http", "https"].contains(scheme) && url.host != nil
}

/// Command-V to the frontmost app; DynamicLake's notch doesn't take focus, so that's the app the user copied for.
private func sendPasteKeystroke() -> Bool {
    guard AXIsProcessTrusted() else { return false }
    let source = CGEventSource(stateID: .combinedSessionState)
    let vKey: CGKeyCode = 9
    let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
    let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
    down?.flags = .maskCommand
    up?.flags = .maskCommand
    down?.post(tap: .cghidEventTap)
    up?.post(tap: .cghidEventTap)
    return true
}

