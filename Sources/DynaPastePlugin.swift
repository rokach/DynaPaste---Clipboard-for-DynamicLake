// MARK: - Plugin

private final class DynaPastePlugin {
    private let client: JSONSocketClient
    private let features = HostFeatures.current
    private let store = ClipStore()
    private let watcher = PasteboardWatcher()
    private let thumbnails = ThumbnailSlots()
    private var settings = loadSettings()
    private var isConfirmingClear = false
    private var filter: ClipFilter = .all
    private var isLakeVisible = false
    private var lakeNeedsSend = true
    private var lastLakeSignature: String?
    private var nextPasteboardPoll = Date.distantPast
    private var nextLakeRefresh = Date.distantPast
    private var copiedActivityUntil: Date?
    /// DynaGlance doesn't show `bottom` and can't be closed by the plugin.
    private var isInGlance = false
    private var copiedFeedback: (id: String, until: Date)?
    private var closeLakeAt: Date?

    init(client: JSONSocketClient) {
        self.client = client
    }

    func run() throws {
        try client.connect()
        store.trim(limit: settings.historyLimit)

        // Strong capture: run() never returns, and a weak self can be released early under -O.
        let timer = Timer(timeInterval: actionLoopInterval, repeats: true) { timer in
            do {
                try self.tick()
            } catch {
                debugLog("fatal \(error)")
                timer.invalidate()
                exit(65)
            }
        }
        RunLoop.main.add(timer, forMode: .common)
        RunLoop.main.run()
    }

    private func tick() throws {
        guard let messages = client.receiveAvailable() else {
            exit(0)
        }
        for message in messages {
            try handle(message)
        }

        let now = Date()
        if now >= nextPasteboardPoll {
            nextPasteboardPoll = now.addingTimeInterval(pasteboardPollInterval)
            reloadSettingsIfChanged()
            if let item = watcher.poll(settings: settings, store: store) {
                store.add(item, limit: settings.historyLimit)
                lakeNeedsSend = true
                if settings.showCopiedActivity, let added = store.items.first {
                    try client.send(copiedActivityPayload(added, features: features))
                    copiedActivityUntil = now.addingTimeInterval(copiedActivityDuration)
                }
            }
        }

        if let until = copiedActivityUntil, now >= until {
            copiedActivityUntil = nil
            try client.send(["schemaVersion": schemaVersion, "type": "dismiss", "activityID": copiedActivityID])
        }

        if let feedback = copiedFeedback, now >= feedback.until {
            copiedFeedback = nil
            lakeNeedsSend = true
        }

        if let closeAt = closeLakeAt, now >= closeAt {
            closeLakeAt = nil
            try client.send(["schemaVersion": schemaVersion, "type": "closeLake"])
        }

        if isLakeVisible, now >= nextLakeRefresh {
            nextLakeRefresh = now.addingTimeInterval(lakeRefreshInterval)
            lakeNeedsSend = true
        }

        if lakeNeedsSend {
            lakeNeedsSend = false
            try sendLake(now: now)
        }
    }

    private func reloadSettingsIfChanged() {
        let latest = loadSettings()
        guard latest != settings else { return }
        settings = latest
        store.trim(limit: settings.historyLimit)
        store.save()
        lakeNeedsSend = true
    }

    private func handle(_ message: [String: Any]) throws {
        switch message["type"] as? String {
        case "lakeOpened":
            isLakeVisible = true
            isInGlance = message["trigger"] as? String == "glance"
            lakeNeedsSend = true
        case "lakeClosed":
            isLakeVisible = false
            // Opens on All next time, not on whatever type was picked last.
            if isConfirmingClear || filter != .all {
                isConfirmingClear = false
                filter = .all
                lakeNeedsSend = true
            }
        case "action":
            guard let actionID = message["actionID"] as? String else { return }
            try handleAction(actionID)
        default:
            break
        }
    }

    private func handleAction(_ actionID: String) throws {
        let parts = actionID.split(separator: ":", maxSplits: 1).map(String.init)
        let command = parts[0]
        let itemID = parts.count > 1 ? parts[1] : nil
        lakeNeedsSend = true

        switch command {
        case "copy", "paste":
            guard let itemID, let item = store.item(itemID) else { return }
            guard watcher.write(item, store: store) else { return }
            store.touch(itemID)
            if command == "paste" {
                if features.lakeLayout, !isInGlance {
                    try client.send(["schemaVersion": schemaVersion, "type": "closeLake"])
                }
                // Give the lake time to close before the keystroke lands.
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.25) {
                    if !sendPasteKeystroke() { requestAccessibility() }
                }
            } else {
                copiedFeedback = (itemID, Date().addingTimeInterval(copiedFeedbackDuration))
                if features.lakeLayout, !isInGlance {
                    closeLakeAt = Date().addingTimeInterval(closeAfterCopyDelay)
                }
            }
        case "pin":
            guard let itemID else { return }
            store.togglePin(itemID)
        case "delete":
            guard let itemID else { return }
            store.delete(itemID)
        case "open":
            guard let itemID, let item = store.item(itemID) else { return }
            open(item)
        case "clear":
            isConfirmingClear.toggle()
        case "clear-confirm":
            store.clearUnpinned()
            isConfirmingClear = false
        case "clear-cancel":
            isConfirmingClear = false
        case "filter":
            guard let raw = itemID, let option = ClipFilter(rawValue: raw) else { return }
            filter = option
        default:
            lakeNeedsSend = false
        }
    }

    private func open(_ item: ClipItem) {
        switch item.kind {
        case .link:
            if let text = item.text?.trimmingCharacters(in: .whitespacesAndNewlines), let url = URL(string: text) {
                NSWorkspace.shared.open(url)
            }
        case .files:
            let urls = (item.filePaths ?? []).map { URL(fileURLWithPath: $0) }
                .filter { FileManager.default.fileExists(atPath: $0.path) }
            if !urls.isEmpty { NSWorkspace.shared.activateFileViewerSelecting(urls) }
        case .image:
            if let url = store.imageURL(for: item) { NSWorkspace.shared.activateFileViewerSelecting([url]) }
        case .text:
            break
        }
    }

    private func sendLake(now: Date) throws {
        guard features.lake else { return }

        guard features.lakeLayout else {
            try sendIfChanged(basicLake(latest: store.ordered.first, now: now))
            return
        }

        let visible = Array(store.ordered.filter(filter.includes).prefix(maxVisibleRows))
        // The glance always shows everything, whatever the lake's filter.
        let glanceItems = Array(store.ordered.prefix(maxGlanceRows))
        let unpinnedCount = store.items.filter { !$0.pinned }.count
        if unpinnedCount == 0 { isConfirmingClear = false }

        var assetIDs: [String: String] = [:]
        if features.imageAssets {
            var pictured: [ClipItem] = []
            for item in glanceItems + visible where (item.kind == .image || item.kind == .files) && !pictured.contains(where: { $0.id == item.id }) {
                pictured.append(item)
            }
            let assignment = thumbnails.assign(pictured, store: store)
            for command in assignment.commands {
                try client.send(command)
            }
            assetIDs = assignment.ids
        }

        let lake = lakeLayout(
            items: visible,
            filter: filter,
            hasUnpinned: unpinnedCount > 0,
            store: store,
            assetIDs: assetIDs,
            copiedID: copiedFeedback?.id,
            isConfirmingClear: isConfirmingClear,
            unpinnedCount: unpinnedCount,
            glanceItems: glanceItems,
            now: now
        )
        try sendIfChanged(lakePayload(lake))
    }

    private func sendIfChanged(_ payload: [String: Any]) throws {
        let data = try JSONSerialization.data(withJSONObject: payload, options: [.sortedKeys])
        let signature = String(decoding: data, as: UTF8.self)
        guard signature != lastLakeSignature else { return }
        try client.send(payload)
        lastLakeSignature = signature
    }
}

// MARK: - CLI

private func printJSON(_ object: [String: Any]) {
    if let data = try? JSONSerialization.data(withJSONObject: object, options: [.sortedKeys]),
       let string = String(data: data, encoding: .utf8) {
        print(string)
    }
}

