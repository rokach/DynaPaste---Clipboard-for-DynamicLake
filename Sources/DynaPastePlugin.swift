private func contextMenu(for item: ClipItem) -> [[String: Any]] {
    var menu: [[String: Any]] = [
        ["title": "Copy", "systemImage": "doc.on.doc", "actionID": "copy:\(item.id)"],
        ["title": "Paste", "systemImage": "arrow.down.doc", "actionID": "paste:\(item.id)"],
        ["title": item.pinned ? "Unpin" : "Pin", "systemImage": item.pinned ? "pin.slash" : "pin", "actionID": "pin:\(item.id)"]
    ]
    switch item.kind {
    case .link:
        menu.append(["title": "Open Link", "systemImage": "safari", "actionID": "open:\(item.id)"])
    case .files, .image:
        menu.append(["title": "Show in Finder", "systemImage": "folder", "actionID": "open:\(item.id)"])
    case .text:
        break
    }
    menu.append(["title": "Remove", "systemImage": "trash", "actionID": "delete:\(item.id)", "role": "destructive"])
    return menu
}

/// What dragging the row out gives; nil when it's too big to send.
private func dragItem(for item: ClipItem, store: ClipStore, textBudget: inout Int) -> [String: Any]? {
    switch item.kind {
    case .link:
        return item.text.map { ["url": $0.trimmingCharacters(in: .whitespacesAndNewlines)] }
    case .text:
        guard let text = item.text, text.count <= maxDragTextLength, text.utf8.count <= textBudget else { return nil }
        textBudget -= text.utf8.count
        return ["text": text]
    case .files:
        return item.filePaths?.first.map { ["filePath": $0] }
    case .image:
        return store.imageURL(for: item).map { ["filePath": $0.path] }
    }
}

