/// The latest copies without the full lake's toolbar; expanding the glance opens the lake for the rest.
private func glanceDesign(items: [ClipItem], store: ClipStore, assetIDs: [String: String], copiedID: String?) -> [String: Any] {
    guard !items.isEmpty else {
        return ["hideHeader": true, "content": emptyContent()]
    }
    var textBudget = maxDragTextBudget / 4
    let rows = items.prefix(maxGlanceRows).map { item in
        glanceRow(item, assetID: assetIDs[item.id], copied: copiedID == item.id, drag: dragItem(for: item, store: store, textBudget: &textBudget))
    }
    return ["hideHeader": true, "content": [["type": "scroll", "id": "glance-list", "spacing": 6, "softFade": "both", "children": rows]]]
}

