    _ = AXIsProcessTrustedWithOptions(options)
}

// MARK: - Thumbnails

private let imageFileExtensions: Set<String> = ["png", "jpg", "jpeg", "heic", "heif", "gif", "tif", "tiff", "bmp", "webp"]

/// What a row's picture is drawn from: the copied image, an image file, or a file's Finder icon.
private func thumbnailSource(for item: ClipItem, store: ClipStore) -> URL? {
    switch item.kind {
    case .image:
        return store.imageURL(for: item)
    case .files:
        return item.filePaths?.first.map { URL(fileURLWithPath: $0) }
    case .text, .link:
        return nil
    }
}

private func renderSquare(_ cgImage: CGImage, cropsToFill: Bool) -> Data? {
    let width = CGFloat(cgImage.width)
    let height = CGFloat(cgImage.height)
    guard width > 0, height > 0,
          let context = CGContext(
            data: nil,
            width: Int(thumbnailPixelSize),
            height: Int(thumbnailPixelSize),
            bitsPerComponent: 8,
            bytesPerRow: 0,
            space: CGColorSpaceCreateDeviceRGB(),
            bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue
          ) else {
        return nil
    }
    context.interpolationQuality = .high
    // Photos fill the square; icons keep their shape.
    let scale = cropsToFill
        ? thumbnailPixelSize / min(width, height)
        : thumbnailPixelSize / max(width, height)
    let drawSize = CGSize(width: width * scale, height: height * scale)
    context.draw(cgImage, in: CGRect(
        x: (thumbnailPixelSize - drawSize.width) / 2,
        y: (thumbnailPixelSize - drawSize.height) / 2,
        width: drawSize.width,
        height: drawSize.height
    ))
    guard let scaled = context.makeImage() else { return nil }
    return NSBitmapImageRep(cgImage: scaled).representation(using: .png, properties: [:])
}

private func thumbnailData(for url: URL) -> Data? {
    let isImage = imageFileExtensions.contains(url.pathExtension.lowercased())
    if isImage,
       let image = NSImage(contentsOf: url),
       let cgImage = image.cgImage(forProposedRect: nil, context: nil, hints: nil) {
        return renderSquare(cgImage, cropsToFill: true)
    }
    guard FileManager.default.fileExists(atPath: url.path) else { return nil }
    let icon = NSWorkspace.shared.icon(forFile: url.path)
    var rect = NSRect(x: 0, y: 0, width: thumbnailPixelSize, height: thumbnailPixelSize)
    guard let cgImage = icon.cgImage(forProposedRect: &rect, context: nil, hints: nil) else { return nil }
    return renderSquare(cgImage, cropsToFill: false)
}

/// Maps the pictures on screen onto the reusable asset ids, sending each picture once.
private final class ThumbnailSlots {
    private var slotItems: [String?] = Array(repeating: nil, count: thumbnailSlotCount)
    private var cache: [String: Data] = [:]

    /// Asset ids for the given items, plus the asset commands to send first.
    func assign(_ items: [ClipItem], store: ClipStore) -> (ids: [String: String], commands: [[String: Any]]) {
        let wanted = Array(items.prefix(thumbnailSlotCount))
        let wantedIDs = Set(wanted.map(\.id))
        var ids: [String: String] = [:]
        var commands: [[String: Any]] = []

        for (slot, itemID) in slotItems.enumerated() {
            if let itemID, wantedIDs.contains(itemID) {
                ids[itemID] = assetID(slot)
            }
        }

        // Hidden items keep their slot until a new picture needs it, so switching filters doesn't resend.
        for item in wanted where ids[item.id] == nil {
            guard let slot = slotItems.firstIndex(where: { $0 == nil })
                    ?? slotItems.firstIndex(where: { !wantedIDs.contains($0 ?? "") }),
                  let data = thumbnail(for: item, store: store) else {
                continue
            }
            slotItems[slot] = item.id
            ids[item.id] = assetID(slot)
            commands.append([
                "schemaVersion": schemaVersion,
                "type": "asset",
                "asset": [
                    "id": assetID(slot),
                    "mimeType": "image/png",
                    "base64Data": data.base64EncodedString()
                ]
            ])
        }

        let slotted = Set(slotItems.compactMap { $0 })
        cache = cache.filter { slotted.contains($0.key) }
        return (ids, commands)
    }

    private func thumbnail(for item: ClipItem, store: ClipStore) -> Data? {
        if let cached = cache[item.id] { return cached }
        guard let url = thumbnailSource(for: item, store: store), let data = thumbnailData(for: url) else { return nil }
        cache[item.id] = data
        return data
    }

    private func assetID(_ slot: Int) -> String { "thumb-\(slot)" }
}

// MARK: - Lake

private enum ClipFilter: String, CaseIterable {
    case all
    case text
    case links
    case images
    case files

    var symbol: String {
        switch self {
        case .all: return "square.grid.2x2"
        case .text: return "textformat.size.larger"
        case .links: return "link"
        case .images: return "photo"
        case .files: return "doc"
        }
    }

    var title: String {
        switch self {
        case .all: return "All"
        case .text: return "Text"
        case .links: return "Links"
        case .images: return "Images"
        case .files: return "Files"
        }
    }

    /// Image files count as images, not files.
    func includes(_ item: ClipItem) -> Bool {
        switch self {
        case .all: return true
        case .text: return item.kind == .text
        case .links: return item.kind == .link
        case .images: return item.kind == .image || isImageFile(item)
        case .files: return item.kind == .files && !isImageFile(item)
        }
    }
}

private func isImageFile(_ item: ClipItem) -> Bool {
    guard item.kind == .files, let path = item.filePaths?.first else { return false }
    return imageFileExtensions.contains(URL(fileURLWithPath: path).pathExtension.lowercased())
}

/// The host rejects control characters and caps text at 240 characters.
private func oneLine(_ text: String, limit: Int = previewLength) -> String {
    let collapsed = text
        .components(separatedBy: .controlCharacters)
        .joined(separator: " ")
        .components(separatedBy: .whitespaces)
        .filter { !$0.isEmpty }
        .joined(separator: " ")
    guard collapsed.count > limit else { return collapsed }
    return String(collapsed.prefix(limit - 1)) + "…"
}

private func relativeTime(_ date: Date, now: Date) -> String {
    let seconds = max(now.timeIntervalSince(date), 0)
    switch seconds {
    case ..<60: return "Now"
    case ..<3600: return "\(Int(seconds / 60))m"
    case ..<86_400: return "\(Int(seconds / 3600))h"
    case ..<(86_400 * 7): return "\(Int(seconds / 86_400))d"
    default:
        let formatter = DateFormatter()
        formatter.setLocalizedDateFormatFromTemplate("MMMd")
        return formatter.string(from: date)
    }
}

private func title(of item: ClipItem) -> String {
    switch item.kind {
    case .text, .link:
        let line = oneLine(item.text ?? "")
        return line.isEmpty ? "Text" : line
    case .files:
        let paths = item.filePaths ?? []
        let first = paths.first.map { URL(fileURLWithPath: $0).lastPathComponent } ?? "Files"
        return oneLine(paths.count > 1 ? "\(first) +\(paths.count - 1)" : first)
    case .image:
        if let size = item.imageSize {
            return "Image \(Int(size.width))×\(Int(size.height))"
        }
        return "Image"
    }
}

private func symbol(of item: ClipItem) -> String {
    switch item.kind {
    case .text: return "textformat.size.larger"
    case .link: return "link"
    case .files: return (item.filePaths?.count ?? 0) > 1 ? "doc.on.doc" : "doc"
    case .image: return "photo"
    }
}

private func tint(of item: ClipItem) -> String {
    switch item.kind {
    case .text: return "white"
    case .link: return "blue"
    case .files: return "cyan"
    case .image: return "purple"
    }
}

private func subtitle(of item: ClipItem, now: Date) -> String {
    var parts: [String] = []
    if item.pinned { parts.append("Pinned") }
    if let sourceApp = item.sourceApp, !sourceApp.isEmpty { parts.append(sourceApp) }
    parts.append(relativeTime(item.date, now: now))
    return oneLine(parts.joined(separator: " · "), limit: 80)
}

private func icon(of item: ClipItem, id: String, assetID: String?, size: Double) -> [String: Any] {
    if let assetID {
        var image: [String: Any] = ["type": "image", "id": id, "source": "asset", "assetID": assetID, "size": size]
        // File icons have their own shape; photos get rounded corners.
        if item.kind == .image || isImageFile(item) {
            image["cornerRadius"] = size * 0.22
            image["contentMode"] = "fill"
        }
        return image
    }
    return ["type": "image", "id": id, "source": "sfSymbol", "systemImage": symbol(of: item), "tint": tint(of: item), "size": size]
}

private func plainButton(id: String, systemImage: String, actionID: String, tint: String, title: String, size: Double = 24) -> [String: Any] {
    [
        "type": "button", "id": id, "systemImage": systemImage, "shape": "plain",
        "actionID": actionID, "tint": tint, "size": size, "title": title
    ]
}

private func capsuleButton(id: String, title: String, systemImage: String, actionID: String, tint: String, destructive: Bool = false, size: Double = 26) -> [String: Any] {
    var button: [String: Any] = [
        "type": "button", "id": id, "title": title, "systemImage": systemImage, "shape": "roundedRect",
        "actionID": actionID, "tint": tint, "size": size
    ]
